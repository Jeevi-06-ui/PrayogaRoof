export function getSubjectById(subjectId: SubjectId): SubjectMetadata | undefined {
  const subject = SUBJECTS.find((s) => s.id === subjectId);
  if (!subject) return undefined;
  const count = getExperimentsBySubject(subjectId).length;
  const implementedCount = getImplementedExperimentsBySubject(subjectId).length;
  return {
    ...subject,
    totalExperiments: count,
    availableExperiments: implementedCount,
  };
}

export function getAllSubjects(): SubjectMetadata[] {
  return SUBJECTS.map((s) => ({
    ...s,
    totalExperiments: getExperimentsBySubject(s.id).length,
    availableExperiments: getImplementedExperimentsBySubject(s.id).length,
  }));
}

export function getActiveSubjects(): SubjectMetadata[] {
  return getAllSubjects().filter((s) => s.status === 'active');
}

export function getExperimentsBySubject(subjectId: SubjectId, classLevel?: ClassLevel): ExperimentMetadata[] {
  return EXPERIMENTS.filter((exp) => {
    const matchesSubject = exp.subjectId === subjectId;
    const matchesClass = !classLevel || exp.classLevel === classLevel;
    return matchesSubject && matchesClass;
  }).sort((a, b) => a.order - b.order);
}

export function getExperimentsByClassLevel(subjectId: SubjectId, classLevel: ClassLevel): ExperimentMetadata[] {
  return getExperimentsBySubject(subjectId, classLevel);
}

export function getImplementedExperimentsBySubject(subjectId: SubjectId): ExperimentMetadata[] {
  return EXPERIMENTS.filter(
    (exp) => exp.subjectId === subjectId && exp.implementationStatus === 'implemented'
  ).sort((a, b) => a.order - b.order);
}

export function getExperimentById(experimentId: string): ExperimentMetadata | undefined {
  return EXPERIMENTS.find((exp) => exp.id === experimentId);
}

export function getAllActiveExperiments(): ExperimentMetadata[] {
  return EXPERIMENTS;
}
